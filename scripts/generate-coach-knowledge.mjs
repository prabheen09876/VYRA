import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// These reviewed Markdown documents are the source of truth. Never import prototype
// Python code or ship its .env, machine paths, or Chroma database in the Worker.
const input = new URL('../apps/worker/knowledge/', import.meta.url);
const output = new URL('../apps/worker/src/coach-knowledge.ts', import.meta.url);
const slug = value => value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const chunks = [];
for (const filename of (await readdir(input)).filter(name => name.endsWith('.md')).sort()) {
  const documentId = filename.slice(0, -3);
  const markdown = (await readFile(new URL(filename, input), 'utf8')).replaceAll('\r\n', '\n');
  let title = ''; let section = ''; let parent = ''; let content = [];
  const flush = () => {
    const text = content.join('\n').trim(); content = [];
    if (!text) return;
    if (!title || !section) throw new Error(`Missing title/section in ${filename}`);
    let part = ''; let index = 0;
    const emit = () => {
      if (part.trim()) chunks.push({ id: `${documentId}:${slug(section)}:${++index}`, documentId, title, section, content: part.trim() });
      part = '';
    };
    for (const paragraph of text.split(/\n\s*\n/)) {
      // Break unusually long paragraphs at a word boundary, keeping every word.
      for (const piece of paragraph.match(/.{1,1100}(?:\s|$)|\S+/gs) ?? []) {
        if (part.length + piece.length + 2 > 1100) emit();
        part += `${part ? '\n\n' : ''}${piece.trim()}`;
      }
    }
    emit();
  };
  for (const line of markdown.split('\n')) {
    const heading = /^(#{1,3}) (.+)$/.exec(line);
    if (!heading) { content.push(line); continue; }
    flush();
    if (heading[1].length === 1) title = heading[2];
    else if (heading[1].length === 2) { parent = heading[2]; section = parent; }
    else section = `${parent} / ${heading[2]}`;
  }
  flush();
}
if (new Set(chunks.map(chunk => chunk.documentId)).size !== 13) throw new Error('Expected all 13 guide documents.');
if (new Set(chunks.map(chunk => chunk.id)).size !== chunks.length) throw new Error('Duplicate knowledge IDs.');
await writeFile(output, `// Generated by scripts/generate-coach-knowledge.mjs. Edit apps/worker/knowledge/*.md instead.\nexport interface KnowledgeChunk { id: string; documentId: string; title: string; section: string; content: string }\nexport const COACH_KNOWLEDGE: readonly KnowledgeChunk[] = ${JSON.stringify(chunks, null, 2)};\n`);
console.log(`Bundled ${chunks.length} sections from 13 guide documents into ${fileURLToPath(output)}.`);
