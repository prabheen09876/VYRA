import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// data/exercises/exercises.json (scraped from simplyfitness.com) is the source of truth.
// This is a pure transform into a committed TS module the Worker imports — mirrors
// generate-coach-knowledge.mjs. Never ship the Python prototype's .env, machine paths,
// or Chroma database in the Worker.
const input = new URL('../data/exercises/exercises.json', import.meta.url);
const output = new URL('../apps/worker/src/exercise-catalog.ts', import.meta.url);

const MUSCLE_GROUPS = ['chest', 'back', 'shoulders', 'biceps', 'triceps', 'abdominals', 'legs', 'calves'];

const dataset = JSON.parse(await readFile(input, 'utf8'));
if (!Array.isArray(dataset.exercises) || !dataset.exercises.length) throw new Error('No exercises in dataset.');

const seen = new Set();
const catalog = dataset.exercises.map(raw => {
  for (const field of ['slug', 'name', 'url', 'subtitle', 'startingPosition', 'execution']) {
    if (typeof raw[field] !== 'string' || !raw[field].trim()) throw new Error(`Exercise ${raw.slug} missing ${field}.`);
  }
  if (seen.has(raw.slug)) throw new Error(`Duplicate slug ${raw.slug}.`);
  seen.add(raw.slug);
  const groups = (list, label) => {
    const values = Array.isArray(list) ? list : [];
    for (const value of values) if (!MUSCLE_GROUPS.includes(value)) throw new Error(`Exercise ${raw.slug} has invalid ${label} "${value}".`);
    return values;
  };
  const primaryMuscles = groups(raw.primaryMuscles, 'primary muscle');
  if (!primaryMuscles.length) throw new Error(`Exercise ${raw.slug} has no primary muscle group.`);
  if (raw.image !== null && (typeof raw.image !== 'string' || !raw.image.startsWith('/exercise-images/'))) {
    throw new Error(`Exercise ${raw.slug} has an unexpected image path.`);
  }
  return {
    slug: raw.slug,
    name: raw.name,
    url: raw.url,
    subtitle: raw.subtitle,
    primaryMuscles,
    secondaryMuscles: groups(raw.secondaryMuscles, 'secondary muscle'),
    muscleLabels: Array.isArray(raw.muscleLabels) ? raw.muscleLabels : [],
    equipment: Array.isArray(raw.equipment) ? raw.equipment : [],
    startingPosition: raw.startingPosition,
    execution: raw.execution,
    image: raw.image ?? null,
    imageSource: typeof raw.imageSource === 'string' ? raw.imageSource : null,
  };
});

const perGroup = Object.fromEntries(MUSCLE_GROUPS.map(g => [g, catalog.filter(e => e.primaryMuscles.includes(g)).length]));
const banner = `// Generated by scripts/generate-exercise-catalog.mjs from data/exercises/exercises.json. Do not edit by hand.\n`;
const body = `import type { CatalogExercise } from '@vyra/core';\n\nexport const EXERCISE_CATALOG: readonly CatalogExercise[] = ${JSON.stringify(catalog, null, 2)};\n`;
await writeFile(output, banner + body);
console.log(`Bundled ${catalog.length} exercises into ${fileURLToPath(output)}.`);
console.log(`Primary group counts: ${JSON.stringify(perGroup)}`);
